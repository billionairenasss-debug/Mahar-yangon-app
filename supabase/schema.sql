create extension if not exists "pgcrypto";

-- ============================================================
-- 1. PRODUCTS
-- ============================================================

create table if not exists public.products (
    id bigint generated by default as identity primary key,

    name text not null,
    description text,

    price numeric(12,2) not null default 0,

    color text,
    sizes text,

    image_url text,

    stock integer not null default 0,

    active boolean not null default true,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint products_price_non_negative
        check (price >= 0),

    constraint products_stock_non_negative
        check (stock >= 0)
);


-- ============================================================
-- 2. CUSTOMERS
-- ============================================================

create table if not exists public.customers (
    id bigint generated by default as identity primary key,

    name text not null,
    phone text not null,

    address text,
    township text,

    note text,

    total_orders integer not null default 0,
    total_spent numeric(12,2) not null default 0,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint customers_total_orders_non_negative
        check (total_orders >= 0),

    constraint customers_total_spent_non_negative
        check (total_spent >= 0)
);


-- ============================================================
-- 3. ORDERS
-- ============================================================

create table if not exists public.orders (
    id bigint generated by default as identity primary key,

    customer_id bigint
        references public.customers(id)
        on delete set null,

    customer_name text not null,
    customer_phone text not null,
    customer_address text,

    total_amount numeric(12,2) not null default 0,

    status text not null default 'pending',

    payment_method text,
    payment_status text not null default 'unpaid',

    note text,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint orders_total_amount_non_negative
        check (total_amount >= 0),

    constraint orders_status_check
        check (
            status in (
                'pending',
                'confirmed',
                'packing',
                'shipped',
                'delivered',
                'cancelled'
            )
        ),

    constraint orders_payment_status_check
        check (
            payment_status in (
                'unpaid',
                'paid',
                'refunded'
            )
        )
);


-- ============================================================
-- 4. ORDER ITEMS
-- ============================================================

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,

    order_id bigint not null
        references public.orders(id)
        on delete cascade,

    product_id bigint
        references public.products(id)
        on delete set null,

    product_name text not null,

    quantity integer not null default 1,

    unit_price numeric(12,2) not null default 0,

    subtotal numeric(12,2) not null default 0,

    created_at timestamptz not null default now(),

    constraint order_items_quantity_positive
        check (quantity > 0),

    constraint order_items_unit_price_non_negative
        check (unit_price >= 0),

    constraint order_items_subtotal_non_negative
        check (subtotal >= 0)
);


-- ============================================================
-- 5. STOCK MOVEMENTS
-- ============================================================

create table if not exists public.stock_movements (
    id bigint generated by default as identity primary key,

    product_id bigint not null
        references public.products(id)
        on delete cascade,

    movement_type text not null,

    quantity integer not null,

    stock_before integer not null default 0,
    stock_after integer not null default 0,

    note text,

    created_at timestamptz not null default now(),

    constraint stock_movement_type_check
        check (
            movement_type in (
                'stock_in',
                'stock_out',
                'adjustment',
                'sale',
                'return'
            )
        ),

    constraint stock_before_non_negative
        check (stock_before >= 0),

    constraint stock_after_non_negative
        check (stock_after >= 0)
);


-- ============================================================
-- 6. CUSTOMER NOTES
-- ============================================================

create table if not exists public.customer_notes (
    id bigint generated by default as identity primary key,

    customer_id bigint not null
        references public.customers(id)
        on delete cascade,

    note text not null,

    created_at timestamptz not null default now()
);


