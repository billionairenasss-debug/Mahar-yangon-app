on public.orders;

create trigger orders_set_updated_at
before update on public.orders
for each row
execute function public.set_updated_at();


-- ============================================================
-- 10. STOCK UPDATE FUNCTION
-- ============================================================

create or replace function public.change_product_stock(
    p_product_id bigint,
    p_quantity integer,
    p_movement_type text,
    p_note text default null
)
returns public.products
language plpgsql
security definer
set search_path = public
as $$
declare
    v_product public.products;
    v_new_stock integer;
begin

    select *
    into v_product
    from public.products
    where id = p_product_id
    for update;

    if not found then
        raise exception 'Product not found';
    end if;

    if p_movement_type in ('stock_in', 'return') then
        v_new_stock := v_product.stock + p_quantity;

    elsif p_movement_type in ('stock_out', 'sale') then
        v_new_stock := v_product.stock - p_quantity;

    elsif p_movement_type = 'adjustment' then
        v_new_stock := p_quantity;

    else
        raise exception 'Invalid stock movement type';
    end if;

    if v_new_stock < 0 then
        raise exception 'Not enough stock';
    end if;

    update public.products
    set
        stock = v_new_stock,
        updated_at = now()
    where id = p_product_id
    returning *
    into v_product;

    insert into public.stock_movements (
        product_id,
        movement_type,
        quantity,
        stock_before,
        stock_after,
        note
    )
    values (
        p_product_id,
        p_movement_type,
        p_quantity,
        case
            when p_movement_type = 'adjustment'
            then v_product.stock
            else
                case
                    when p_movement_type in ('stock_in', 'return')
                    then v_product.stock - p_quantity
                    else v_product.stock + p_quantity
                end
        end,
        v_new_stock,
        p_note
    );

    return v_product;
end;
$$;


-- ============================================================
-- 11. CUSTOMER SUMMARY FUNCTION
-- ============================================================

create or replace function public.refresh_customer_summary(
    p_customer_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin

    update public.customers c
    set
        total_orders = (
            select count(*)
            from public.orders o
            where o.customer_id = p_customer_id
              and o.status <> 'cancelled'
        ),

        total_spent = (
            select coalesce(sum(o.total_amount), 0)
            from public.orders o
            where o.customer_id = p_customer_id
              and o.status <> 'cancelled'
              and o.payment_status = 'paid'
        ),

        updated_at = now()

    where c.id = p_customer_id;

end;
$$;


