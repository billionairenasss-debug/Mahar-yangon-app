-- 12. PRODUCT VIEW
-- ============================================================

create or replace view public.active_products
as
select
    id,
    name,
    description,
    price,
    color,
    sizes,
    image_url,
    stock,
    active,
    created_at,
    updated_at
from public.products
where active = true
order by created_at desc;


-- ============================================================
-- 13. CUSTOMER ORDER HISTORY VIEW
-- ============================================================

create or replace view public.customer_order_history
as
select
    o.id as order_id,
    o.customer_id,
    o.customer_name,
    o.customer_phone,
    o.customer_address,
    o.total_amount,
    o.status,
    o.payment_method,
    o.payment_status,
    o.note,
    o.created_at,

    count(oi.id) as item_count

from public.orders o

left join public.order_items oi
    on oi.order_id = o.id

group by
    o.id,
    o.customer_id,
    o.customer_name,
    o.customer_phone,
    o.customer_address,
    o.total_amount,
    o.status,
    o.payment_method,
    o.payment_status,
    o.note,
    o.created_at;


